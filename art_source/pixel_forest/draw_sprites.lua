local im,ox,oy
local function p(x,y,c) im:drawPixel(x+ox,y+oy,C[c]) end
local function r(x,y,w,h,c) for j=y,y+h-1 do for i=x,x+w-1 do p(i,j,c) end end end
local function poly(v,c)
 local miny,maxy=999,-999
 for _,a in ipairs(v) do miny=math.min(miny,a[2]);maxy=math.max(maxy,a[2]) end
 for y=miny,maxy do
  local xs={}
  for i,a in ipairs(v) do local b=v[i%#v+1]; if (a[2]<=y and b[2]>y) or (b[2]<=y and a[2]>y) then xs[#xs+1]=a[1]+(y-a[2])*(b[1]-a[1])/(b[2]-a[2]) end end
  table.sort(xs);for i=1,#xs-1,2 do for x=math.ceil(xs[i]),math.floor(xs[i+1]) do p(x,y,c) end end
 end
end
local function e(x,y,w,h,c) for j=0,h-1 do for i=0,w-1 do if ((i+.5-w/2)/(w/2))^2+((j+.5-h/2)/(h/2))^2<=1 then p(x+i,y+j,c) end end end end
